"""
wsgi.py — точка входа для gunicorn (веб-часть: приём вебхуков от сайта).

ОТДЕЛЬНО от run.py (который отвечает ТОЛЬКО за Telegram-поллинг).

Почему это два разных файла, а не один процесс, как раньше:
gunicorn может поднимать несколько worker-процессов для надёжности
и параллельной обработки запросов. Если бы этот файл импортировал
main.py целиком (там создаётся TeleBot и запускается polling), каждый
gunicorn-воркер завёл бы СВОЙ процесс опроса Telegram с одним и тем же
токеном — это ровно тот 409 Conflict, который мы specifically чинили
на bothost. Поэтому здесь создаётся отдельный, лёгкий экземпляр TeleBot,
который используется ТОЛЬКО для отправки исходящих уведомлений
(bot.send_message из вебхуков) — он не регистрирует ни одного обработчика
и никогда не вызывает infinity_polling(), поэтому безопасно иметь по
одному такому объекту в каждом gunicorn-воркере.

Реальный Telegram-поллинг (обработка входящих сообщений/кнопок) живёт
отдельно — в run.py, под управлением systemd (musculata-bot.service),
как и раньше. Эти две точки входа независимы и могут перезапускаться
одна без другой.

Запуск (см. musculata-webhooks.service):
    gunicorn --bind 127.0.0.1:5000 --workers 2 wsgi:app
"""

import logging_setup  # noqa: F401 — настраивает логирование в файл при импорте

import telebot

from config import BOT_TOKEN
import webhooks

# Лёгкий клиент бота — только для исходящих уведомлений. НЕ регистрирует
# обработчики, НЕ вызывает infinity_polling(). Безопасно создавать по
# экземпляру на каждый gunicorn-воркер — конфликта с процессом поллинга
# (musculata-bot.service, run.py) быть не может, потому что этот объект
# никогда не спрашивает Telegram про новые обновления (getUpdates).
_notifier_bot = telebot.TeleBot(BOT_TOKEN)
webhooks.set_bot_instance(_notifier_bot)

# gunicorn ищет переменную с именем "app" по умолчанию (wsgi:app)
app = webhooks.app
